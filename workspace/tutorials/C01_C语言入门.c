/* ============================================================
   C01：C 语言入门——从 printf 和变量开始
   ============================================================
   【本课目标】
   1. 知道 C 程序从 main 开始，按顺序执行。
   2. 会用 printf 输出文字和数字。
   3. 认识 int、float、char 三种最常用的类型。
   4. 会用 scanf 读取一个整数。

   【运行说明】
   靶场会先编译再运行。看到“输入一个整数”时，
   在下方输入框输入数字并回车。
   ============================================================ */

#include <stdio.h>

int main(void) {
    /* 让 printf 立即输出。管道模式下 stdout 默认是全缓冲，
       如果不加这一行，scanf 前的提示可能等程序结束才出现。 */
    setbuf(stdout, NULL);

    printf("你好，C！\n");
    printf("这是第一行 C 代码。\n\n");

    /* --------------------------------------------------------
       一、变量：给数据起名字
       --------------------------------------------------------
       int 用来存整数；float 用来存小数；char 用来存单个字符。
       变量必须先声明类型，再使用。 */
    int age = 20;
    float length = 80.5;
    char grade = 'A';

    printf("age = %d\n", age);
    printf("length = %.1f\n", length);
    printf("grade = %c\n", grade);

    /* --------------------------------------------------------
       二、printf 的格式符
       --------------------------------------------------------
       %d 整数，%f 小数，%c 单个字符，%s 字符串。
       格式符和后面的参数必须一一对应。 */
    printf("\nage 加 1 = %d\n", age + 1);
    printf("length 乘 2 = %.2f\n", length * 2);
    printf("字符的 ASCII 码 = %d\n", grade);

    /* --------------------------------------------------------
       三、读取输入
       --------------------------------------------------------
       scanf 需要变量的地址，所以 n 前面要加 &。
       如果输入的不是整数，scanf 会返回 0，程序要处理这种情况。 */
    int n = 0;
    printf("\n输入一个整数：");
    if (scanf("%d", &n) != 1) {
        printf("没有读到整数。\n");
        return 1;
    }

    printf("你输入了 %d，它的平方是 %d。\n", n, n * n);

    /* --------------------------------------------------------
       四、常见错误
       --------------------------------------------------------
       1. 忘写分号：C 的每条语句末尾都要有分号。
       2. printf 的格式符和参数类型不匹配。
       3. scanf 忘记 &，程序可能崩溃或读不到值。
       4. 中文标点不能出现在代码里；字符串里的中文可以。
       5. main 写成 mian，链接时会找不到入口。

       五、动手练习（复制练习后完成）
       1. 再声明一个 int 变量，输出它的两倍。
       2. 用 scanf 读两个整数，输出它们的和。
       3. 故意删掉一个分号，观察编译器报什么错。
       -------------------------------------------------------- */

    printf("\nC01 结束：C 程序从 main 开始，一条一条执行。\n");
    return 0;
}
