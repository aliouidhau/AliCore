# ============================================================
# 第 6 课：循环——把重复劳动交给程序
# ============================================================
# 【本课目标】
# 1. 会用 for 遍历和 range 计数。
# 2. 理解 while 的执行条件。
# 3. 会用 break、continue，并避免死循环。

# ------------------------------------------------------------
# 一、for：逐个处理一组数据
# ------------------------------------------------------------
# 下面这段读作：对于 parts 里的每一个元素，把它叫作 part，然后执行缩进代码。

parts = ["底座", "支架", "盖板"]

for part in parts:
    print("正在检查：", part)

# 循环结束后，继续执行循环外的代码。
print("全部检查完毕")

# ------------------------------------------------------------
# 二、range：生成一串整数
# ------------------------------------------------------------
# range(5)       得到 0、1、2、3、4，不包含 5。
# range(1, 6)    得到 1 到 5。
# range(0, 10, 2) 从 0 开始，每次加 2，得到 0、2、4、6、8。

print("range(5)：")
for i in range(5):
    print(i)

print("编号从 1 开始：")
for i in range(1, 4):
    print(f"零件_{i:02d}")   # :02d 表示整数至少两位，不足补 0

# ------------------------------------------------------------
# 三、循环里累加
# ------------------------------------------------------------
# 先准备一个初始值，再每轮更新。变量必须定义在循环外。

scores = [80, 90, 85]
total = 0

for score in scores:
    total += score

average = total / len(scores)
print("总分：", total)
print("平均分：", average)

# ------------------------------------------------------------
# 四、enumerate：既拿位置，又拿内容
# ------------------------------------------------------------
# 需要编号时，不必自己再维护一个计数器。

for index, part in enumerate(parts, start=1):
    print(f"第 {index} 个零件：{part}")

# ------------------------------------------------------------
# 五、while：条件成立就继续
# ------------------------------------------------------------
# while 适合“不知道具体要重复几次，但知道什么时候停”的场景。
# 每一轮都要让条件有机会变成 False。

count = 0
while count < 3:
    print("while 当前计数：", count)
    count += 1

# 如果漏掉 count += 1，count 永远小于 3，就会形成死循环。
# 练习场运行超过 15 秒会强制停止，但写代码时仍要主动避免。

# ------------------------------------------------------------
# 六、break 与 continue
# ------------------------------------------------------------
# break：立即结束整个循环。
# continue：跳过本轮剩下的代码，进入下一轮。

numbers = [3, 7, 0, 9, 12]

print("遇到 0 就停止：")
for n in numbers:
    if n == 0:
        break
    print(n)

print("跳过 0，只处理非零数字：")
for n in numbers:
    if n == 0:
        continue
    print("100 /", n, "=", 100 / n)

# ------------------------------------------------------------
# 七、课堂练习：找合格零件
# ------------------------------------------------------------
# 给定 6 个轴径测量值，要求 19.8～20.2。
# 请循环打印每个测量值是否合格，最后统计合格数量。

measurements = [20.01, 19.75, 20.10, 20.30, 19.90, 20.00]
qualified_count = 0

for index, value in enumerate(measurements, start=1):
    if 19.8 <= value <= 20.2:
        print(f"第 {index} 个：{value}，合格")
        qualified_count += 1
    else:
        print(f"第 {index} 个：{value}，不合格")

print("合格数量：", qualified_count)

print("\n第 6 课结束：有固定数据用 for，有条件持续用 while。")
