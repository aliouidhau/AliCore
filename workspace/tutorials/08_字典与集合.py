# ============================================================
# 第 8 课：字典与集合——按名字查数据，自动去重
# ============================================================
# 【本课目标】
# 1. 会用字典保存“键和值”的对应关系。
# 2. 会安全读取、修改、遍历字典。
# 3. 知道集合 set 的去重和成员判断用途。

# ------------------------------------------------------------
# 一、字典：给每项数据一个名字
# ------------------------------------------------------------
# 列表适合“第几个”，字典适合“叫什么”。
# 字典写成 {键: 值}，下面用一个字典描述零件。

part = {
    "name": "矩形块",
    "length": 80,
    "width": 50,
    "height": 10,
}

print("零件名称：", part["name"])
print("零件长度：", part["length"])

# 直接读不存在的键会报 KeyError：
# print(part["material"])

# ------------------------------------------------------------
# 二、get：更安全的读取方式
# ------------------------------------------------------------
# get 找不到键时默认返回 None，也可以指定默认值。
# 不确定键是否存在时，get 比直接下标更稳。

print("材料：", part.get("material"))
print("材料（带默认值）：", part.get("material", "未指定"))

# ------------------------------------------------------------
# 三、新增与修改
# ------------------------------------------------------------
# 对同一个键赋值：键不存在就是新增，键已存在就是修改。

part["material"] = "铝合金"   # 新增
part["height"] = 12          # 修改
print("更新后的零件：", part)

# del 删除一个键值对。
del part["width"]
print("删除 width 后：", part)

# ------------------------------------------------------------
# 四、遍历字典
# ------------------------------------------------------------
# items() 同时拿键和值，是最常用的遍历方式。

for key, value in part.items():
    print(f"{key}: {value}")

print("所有键：", list(part.keys()))
print("所有值：", list(part.values()))

# ------------------------------------------------------------
# 五、字典和列表配合
# ------------------------------------------------------------
# 一个字典描述一个零件，多个字典放进列表，就能描述一批零件。

inventory = [
    {"name": "底座", "quantity": 2},
    {"name": "支架", "quantity": 4},
    {"name": "盖板", "quantity": 1},
]

print("\n库存清单：")
for item in inventory:
    print(f"{item['name']}：{item['quantity']} 件")

total_quantity = sum(item["quantity"] for item in inventory)
print("总数量：", total_quantity)

# ------------------------------------------------------------
# 六、集合 set：不重复、无顺序
# ------------------------------------------------------------
# 集合用花括号，但不写键值对。
# 它最常见的用途：去重、判断是否存在、比较两组数据。

tags = ["机械", "CAD", "机械", "Python", "CAD"]
unique_tags = set(tags)
print("\n去重后的标签：", unique_tags)

# 集合不保证显示顺序，不要用下标取集合元素。
# 可以添加、删除、判断存在。
unique_tags.add("制造")
unique_tags.discard("Python")
print("更新后的标签：", unique_tags)
print("是否包含 CAD：", "CAD" in unique_tags)

# 集合运算：交集 &、并集 |、差集 -。
student_a = {"Python", "CAD", "数学"}
student_b = {"Python", "英语", "CAD"}
print("共同课程：", student_a & student_b)
print("全部课程：", student_a | student_b)
print("A 有而 B 没有：", student_a - student_b)

# ------------------------------------------------------------
# 七、课堂练习：汇总两种零件数量
# ------------------------------------------------------------
# given_records 里同一个零件出现多次。
# 目标：用字典统计每种零件的总数。

given_records = [
    ("底座", 2),
    ("支架", 4),
    ("底座", 1),
    ("盖板", 3),
    ("支架", 2),
]

summary = {}
for name, quantity in given_records:
    # 如果 name 已存在，读旧值；不存在就从 0 开始。
    summary[name] = summary.get(name, 0) + quantity

print("\n汇总结果：", summary)

print("\n第 8 课结束：字典按键找值，集合负责去重和关系运算。")
