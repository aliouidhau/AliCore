/* ============================================================
   C03：条件与循环——让程序会判断、会重复
   ============================================================
   【本课目标】
   1. 会用 if / else if / else 做分支。
   2. 会用 for、while、do-while 做循环。
   3. 知道 break 和 continue 的作用。
   4. 能写出“有明确退出条件”的循环。

   本课不需要输入。
   ============================================================ */

#include <stdio.h>

int main(void) {
    setbuf(stdout, NULL);

    /* --------------------------------------------------------
       一、if / else
       --------------------------------------------------------
       条件为真（非 0）时执行 if 块，否则执行 else 块。 */
    int volume = 42000;

    if (volume < 10000) {
        printf("小件\n");
    } else if (volume < 50000) {
        printf("中件\n");
    } else {
        printf("大件\n");
    }

    /* 条件里常见错误：if (volume = 0) 是赋值，不是比较。
       正确写法是 if (volume == 0)。 */

    /* --------------------------------------------------------
       二、for 循环
       --------------------------------------------------------
       适合“次数已知”的重复。
       三段分别是：初始化；继续条件；每轮结束后的更新。 */
    int sum = 0;
    int i;
    for (i = 1; i <= 10; i++) {
        sum += i;
    }
    printf("\n1 到 10 的和：%d\n", sum);

    /* 循环变量 i 在循环结束后仍然存在，值是 11。 */
    printf("循环结束后 i = %d\n", i);

    /* --------------------------------------------------------
       三、while 循环
       --------------------------------------------------------
       适合“次数未知，但知道什么时候停”的重复。
       每轮都必须让条件朝着结束方向发展，否则会死循环。 */
    int countdown = 5;
    printf("\n倒计时：");
    while (countdown > 0) {
        printf("%d ", countdown);
        countdown--;
    }
    printf("\n");

    /* --------------------------------------------------------
       四、do-while
       --------------------------------------------------------
       先执行一次，再判断条件。
       至少执行一次的场景可以用它。 */
    int tries = 0;
    do {
        tries++;
        printf("第 %d 次尝试\n", tries);
    } while (tries < 3);

    /* --------------------------------------------------------
       五、break 和 continue
       --------------------------------------------------------
       break 直接结束整个循环；continue 跳过本轮剩余代码。 */
    printf("\n找到第一个能被 7 整除的数：");
    for (i = 1; i <= 30; i++) {
        if (i % 7 != 0) {
            continue;
        }
        printf("%d\n", i);
        break;
    }

    /* --------------------------------------------------------
       六、嵌套循环
       --------------------------------------------------------
       外层跑一次，内层跑一整轮。
       嵌套层数越多，复杂度增长越快，能拆就拆。 */
    printf("\n乘法表的一部分：\n");
    for (i = 1; i <= 3; i++) {
        int j;
        for (j = 1; j <= 3; j++) {
            printf("%d×%d=%-3d ", i, j, i * j);
        }
        printf("\n");
    }

    /* --------------------------------------------------------
       七、常见错误
       --------------------------------------------------------
       1. while 条件永远为真，写出死循环。
       2. for 的第三段忘记更新循环变量。
       3. if 后面多写分号：if (x > 0); 代码块会变成空语句。
       4. = 和 == 混用。
       5. 循环里修改循环变量，导致次数不可预测。

       八、动手练习
       1. 输出 1 到 100 中所有偶数。
       2. 用 while 计算一个整数的位数。
       3. 用嵌套循环打印 5 行金字塔（先用空格和星号）。
       -------------------------------------------------------- */

    printf("\nC03 结束：循环一定要能停下来。\n");
    return 0;
}
