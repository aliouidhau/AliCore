# ------------------------------------------------------------
# 一、程序是怎样运行的？
# ------------------------------------------------------------
# 老师讲解：
# 你可以把 Python 想成一个很听话、但不会猜心思的助手。
# 你写一行，它执行一行；默认从文件最上方执行到最下方。
# 下面三行会严格按照 1、2、3 的顺序输出。

print("第一步：你好，Python")
print("第二步：我正在学习编程")
print("第三步：程序按顺序执行")

# ------------------------------------------------------------
# 二、print() 是什么？
# ------------------------------------------------------------
# print 的意思是“打印”。括号里的内容会被送到输出区。
# 文字要放在引号里，单引号、双引号都可以。
# 数字不是文字，可以直接写，不需要引号。

print("这是文字")
print('这也是文字')
print(2026)
print(3.14)

# 一次打印多项内容，用逗号隔开，Python 会自动加空格。
print("我今年", 20, "岁")

# ------------------------------------------------------------
# 三、注释：写给人看的文字
# ------------------------------------------------------------
# 以 # 开头的内容是注释，Python 不会执行它。
# 注释不是废话，它是在告诉未来的你：这段代码为什么这样写。
# 你现在看到的整段课程讲解，也全都写在注释里。

print("这行会执行")
# print("这行被注释了，不会执行")

# ------------------------------------------------------------
# 四、缩进：Python 的格式纪律
# ------------------------------------------------------------
# Python 对行首空格很敏感。现在你只要先记住：
# 普通代码不要随意在行首加空格，顶格写。
# 以后学到 if、for、def 时，缩进会用来表示“谁属于谁”。
#
# 错误示例（不要取消注释，否则会报 IndentationError）：
#     print("这行无缘无故缩进了")

# ------------------------------------------------------------
# 五、常见错误：括号与引号要成对
# ------------------------------------------------------------
# 错误 1：少了右引号
# print("你好)
#
# 错误 2：中文括号。代码里的标点必须用英文标点。
# print（"你好"）
#
# 报错不是坏事。报错是在告诉你：哪一行、哪一类规则出了问题。

