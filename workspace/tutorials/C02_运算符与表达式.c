/* ============================================================
   C02：运算符与表达式——让数据参与计算
   ============================================================
   【本课目标】
   1. 会用算术运算符 + - * / %。
   2. 理解整数除法和小数除法的区别。
   3. 会用关系运算符和逻辑运算符。
   4. 知道类型转换什么时候发生。

   本课不需要输入，直接运行看结果。
   ============================================================ */

#include <stdio.h>

int main(void) {
    setbuf(stdout, NULL);

    int a = 17;
    int b = 5;

    printf("a = %d, b = %d\n", a, b);

    /* --------------------------------------------------------
       一、算术运算符
       --------------------------------------------------------
       + - * 都很直观；/ 要特别注意：两个整数相除，结果还是整数。 */
    printf("\n加法：%d\n", a + b);
    printf("减法：%d\n", a - b);
    printf("乘法：%d\n", a * b);
    printf("整数除法：%d\n", a / b);       /* 17 / 5 = 3，小数部分被丢掉 */
    printf("取余：%d\n", a % b);           /* 17 % 5 = 2 */
    printf("小数除法：%.2f\n", (float)a / b);

    /* --------------------------------------------------------
       二、关系运算符
       --------------------------------------------------------
       == 判断相等，= 是赋值，二者完全不同。
       > < >= <= != 也常用于条件判断。 */
    printf("\n17 == 5 吗：%d\n", a == b);
    printf("17 > 5 吗：%d\n", a > b);
    printf("17 != 5 吗：%d\n", a != b);
    printf("注意：C 里没有布尔类型时，0 表示假，非 0 表示真。\n");

    /* --------------------------------------------------------
       三、逻辑运算符
       --------------------------------------------------------
       && 并且，|| 或者，! 取反。
       它们会把 0 当假，把非 0 当真。 */
    int is_adult = 1;
    int has_ticket = 0;

    printf("\n成年并且有票：%d\n", is_adult && has_ticket);
    printf("成年或者有票：%d\n", is_adult || has_ticket);
    printf("没有票：%d\n", !has_ticket);

    /* --------------------------------------------------------
       四、自增、自减和复合赋值
       --------------------------------------------------------
       ++ 让变量加 1，-- 让变量减 1。
       +=、-=、*=、/= 是“先算再存回去”的简写。 */
    int counter = 10;
    counter++;
    printf("\ncounter++ 之后：%d\n", counter);

    counter += 5;
    printf("counter += 5 之后：%d\n", counter);

    counter *= 2;
    printf("counter *= 2 之后：%d\n", counter);

    /* --------------------------------------------------------
       五、类型转换
       --------------------------------------------------------
       把整数赋给 float 会自动转换；把 float 赋给 int 会截断小数。
       需要精确控制时，写显式转换 (类型)。 */
    int whole = (int)3.99;
    float decimal = 7 / 2;          /* 先做整数除法，再转 float，结果是 3.0 */
    float correct = (float)7 / 2;   /* 先把 7 转成小数，再除，结果是 3.5 */

    printf("\n(int)3.99 = %d\n", whole);
    printf("7 / 2 赋给 float = %.1f\n", decimal);
    printf("(float)7 / 2 = %.1f\n", correct);

    /* --------------------------------------------------------
       六、常见错误
       --------------------------------------------------------
       1. 把 == 写成 =，条件永远成立或赋值成功。
       2. 以为 1 / 2 等于 0.5；整数除法会得到 0。
       3. 对浮点数用 %，编译器不允许。
       4. 复合赋值和自增混用太多，阅读顺序混乱。
       5. 忘记运算符优先级，必要时加括号。

       七、动手练习
       1. 计算半径为 10 的圆面积，输出两位小数。
       2. 用 % 判断一个整数是奇数还是偶数。
       3. 比较 (float)1 / 3 和 1.0 / 3 的输出。
       -------------------------------------------------------- */

    printf("\nC02 结束：先想清楚类型，再写运算符。\n");
    return 0;
}
