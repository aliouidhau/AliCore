# ============================================================
# 第 10 课：文件读写——让程序保存结果
# ============================================================
# 【本课目标】
# 1. 会用 with open 读写文本文件。
# 2. 理解 r、w、a 三种模式的区别。
# 3. 会用 pathlib 处理路径，避免中文乱码。

# ------------------------------------------------------------
# 一、为什么要操作文件？
# ------------------------------------------------------------
# 变量只在程序运行时存在，程序结束就没了。
# 写进文件，结果才能留到下一次使用。

from pathlib import Path

# 当前练习场运行代码时，工作目录就是当前 .py 文件所在目录。
# 这里准备一个相对路径文件，不依赖某台电脑的绝对路径。
file_path = Path("课堂笔记.txt")

# ------------------------------------------------------------
# 二、写文件：w 模式
# ------------------------------------------------------------
# "w" 表示写入。文件已存在时，会先清空旧内容再写。
# encoding="utf-8" 很重要，能避免中文在别的编辑器里乱码。
# with 会在代码块结束后自动关闭文件，即使中途出错也会关闭。

with file_path.open("w", encoding="utf-8") as f:
    f.write("Python 学习笔记\n")
    f.write("第 10 课：文件读写\n")

print("已写入：", file_path)

# ------------------------------------------------------------
# 三、读文件：r 模式
# ------------------------------------------------------------
# "r" 表示读取，是默认模式。
# read() 一次读完全部文本，适合小文件。

with file_path.open("r", encoding="utf-8") as f:
    content = f.read()

print("读到的完整内容：")
print(content)

# ------------------------------------------------------------
# 四、追加：a 模式
# ------------------------------------------------------------
# "a" 表示 append，在文件末尾追加，不会清空旧内容。
# 写日志、连续记录实验数据时很常用。

with file_path.open("a", encoding="utf-8") as f:
    f.write("追加一行：程序结束后，笔记仍然保留。\n")

with file_path.open("r", encoding="utf-8") as f:
    lines = f.readlines()

print("逐行读取，共", len(lines), "行：")
for index, line in enumerate(lines, start=1):
    # strip() 去掉每行末尾的换行符，避免多空一行。
    print(f"第 {index} 行：{line.strip()}")

# ------------------------------------------------------------
# 五、路径与文件检查
# ------------------------------------------------------------
# Path 的 / 可以拼接路径，比手动拼斜杠更稳。

folder = Path("练习数据")
folder.mkdir(exist_ok=True)       # 文件夹已存在也不报错
report_path = folder / "报告.txt"

report_path.write_text("第一份自动生成的报告\n", encoding="utf-8")
print("报告是否存在：", report_path.exists())
print("报告内容：", report_path.read_text(encoding="utf-8"))

# ------------------------------------------------------------
# 六、写多行数据：把程序结果存成表格文本
# ------------------------------------------------------------
# 下面把零件名称和数量写成简单 CSV（逗号分隔文本）。
# Excel 也能打开 CSV；真正做复杂表格时再学习专门库。

records = [
    ("底座", 2),
    ("支架", 4),
    ("盖板", 1),
]

csv_path = folder / "零件清单.csv"
with csv_path.open("w", encoding="utf-8") as f:
    f.write("零件,数量\n")
    for name, quantity in records:
        f.write(f"{name},{quantity}\n")

print("CSV 内容：")
print(csv_path.read_text(encoding="utf-8"))

# ------------------------------------------------------------
# 七、课堂练习
# ------------------------------------------------------------
# 1. 新建一个“学习总结.txt”。
# 2. 写入三行：日期、今天学到的内容、明天的计划。
# 3. 再读出来打印。

summary_path = Path("学习总结.txt")
summary_path.write_text(
    "日期：2026-11-22\n内容：学会文件读写\n计划：继续学习异常处理\n",
    encoding="utf-8",
)
print("学习总结：")
print(summary_path.read_text(encoding="utf-8"))

print("\n第 10 课结束：记住 with、utf-8，以及 w 会清空、a 会追加。")
