# ------------------------------------------------------------
# 一、基本算术
# ------------------------------------------------------------
# + 加，- 减，* 乘，/ 除。
# 注意：Python 里乘法是星号 *，不是字母 x。

length = 80
width = 50
height = 10

area = length * width
volume = area * height
print("面积：", area, "平方毫米")
print("体积：", volume, "立方毫米")

# ------------------------------------------------------------
# 二、/、//、% 到底有什么区别？
# ------------------------------------------------------------
# /   真除法，结果通常是 float。
# //  整除，只保留商的整数部分。
# %   取余数，常用于判断能否整除。

print("7 / 2 =", 7 / 2)
print("7 // 2 =", 7 // 2)
print("7 % 2 =", 7 % 2)

# 实际例子：100 个零件，每箱装 24 个。
parts = 100
per_box = 24
full_boxes = parts // per_box
remaining = parts % per_box
print(f"满箱 {full_boxes} 箱，剩余 {remaining} 个")

# ------------------------------------------------------------
# 三、幂运算与复合赋值
# ------------------------------------------------------------
# ** 表示幂：2 ** 3 是 2 的三次方。
print("2 的 3 次方：", 2 ** 3)
print("5 的平方：", 5 ** 2)

# += 是“在自己基础上增加”的简写。
count = 10
count += 5       # 等价于 count = count + 5
print("增加后的数量：", count)

# ------------------------------------------------------------
# 四、运算优先级
# ------------------------------------------------------------
# 和数学一样：先乘除，后加减；不确定就加括号。
# 括号不仅防止错误，也让别人更容易看懂。

result_1 = 10 + 20 * 3
result_2 = (10 + 20) * 3
print("10 + 20 * 3 =", result_1)
print("(10 + 20) * 3 =", result_2)

# ------------------------------------------------------------
# 五、小数与四舍五入
# ------------------------------------------------------------
# 计算机存小数有精度限制，0.1 + 0.2 不一定正好显示 0.3。
# 做一般学习计算不用担心；展示结果时可以用 round 或格式化。

print("0.1 + 0.2 =", 0.1 + 0.2)
print("保留两位：", round(0.1 + 0.2, 2))

ratio = 2 / 3
print(f"比例保留两位：{ratio:.2f}")
print(f"百分比保留一位：{ratio:.1%}")

# ------------------------------------------------------------
# 六、math 模块
# ------------------------------------------------------------
# 模块是别人写好的工具包。import 后就能使用里面的功能。

import math

print("圆周率：", math.pi)
print("平方根：", math.sqrt(25))
print("向上取整：", math.ceil(4.2))
print("向下取整：", math.floor(4.8))

# 圆面积：π × 半径²
radius = 25
circle_area = math.pi * radius ** 2
print(f"半径 {radius} 的圆面积：{circle_area:.2f} 平方毫米")

# ------------------------------------------------------------
# 七、课堂练习：圆柱体积
# ------------------------------------------------------------
# 已知圆柱半径 30 mm，高 100 mm。
# 公式：体积 = π × 半径² × 高。

cylinder_radius = 30
cylinder_height = 100
cylinder_volume = math.pi * cylinder_radius ** 2 * cylinder_height
print(f"圆柱体积：{cylinder_volume:.2f} 立方毫米")

print("\n第 4 课结束：先想清楚公式，再把公式逐字翻译成代码。")
