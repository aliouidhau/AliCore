# 第 3 课：字符串——把文字处理明白
# ============================================================
# 【本课目标】
# 1. 会拼接、格式化字符串。
# 2. 会取下标、切片。
# 3. 掌握几个最常用的字符串方法。

# ------------------------------------------------------------
# 一、字符串的三种常见写法
# ------------------------------------------------------------
# 单引号和双引号基本等价，三引号适合多行文字。

name = '阿鲤'
school = "装备制造"
message = """第一行
第二行
第三行"""

print(name)
print(school)
print(message)

# 字符串里有双引号时，可以外面用单引号，减少转义。
print('他说："先理解，再背语法。"')

# ------------------------------------------------------------
# 二、拼接与 f-string
# ------------------------------------------------------------
# 加号 + 可以把两段字符串接起来，但两边必须都是字符串。

name = "学生甲"
major = "机械工程"
print("姓名：" + name + "，专业：" + major)

# 更推荐 f-string：字符串前加 f，变量放进 {}。
# 它的好处是结构清楚，变量多了也不容易乱。
print(f"姓名：{name}，专业：{major}")

length = 80
width = 50
print(f"零件尺寸：{length} × {width}，面积：{length * width}")

# ------------------------------------------------------------
# 三、下标：按位置取一个字符
# ------------------------------------------------------------
# Python 从 0 开始数位置。
# 下标 0 是第一个字符，-1 是最后一个字符。

word = "PYTHON"
print("完整字符串：", word)
print("第一个字符：", word[0])
print("第三个字符：", word[2])
print("最后一个字符：", word[-1])

# 下标不能超过范围，否则会报 IndexError。
# print(word[100])

# ------------------------------------------------------------
# 四、切片：取一段字符
# ------------------------------------------------------------
# 格式：字符串[开始:结束]
# 重点：包含开始位置，不包含结束位置。

print("前三个：", word[0:3])
print("从第三个到最后：", word[2:])
print("前三个的简写：", word[:3])
print("倒序：", word[::-1])

# ------------------------------------------------------------
# 五、常用方法
# ------------------------------------------------------------
# 方法可以理解为“这个数据自带的功能”，用点号调用。

text = "  Python For Mechanical Design  "
print("原文字：", repr(text))
print("去首尾空格：", text.strip())
print("全小写：", text.lower())
print("全大写：", text.upper())
print("替换：", text.strip().replace("Mechanical", "Mechanical CAD"))
print("长度：", len(text.strip()))

# 判断字符串里是否包含某段内容，用 in。
print("是否包含 Python：", "Python" in text)

# split 可以按分隔符拆开，结果先知道是“几段文字”即可。
parts = "底座,支架,盖板".split(",")
print("拆分结果：", parts)

# ------------------------------------------------------------
# 六、课堂练习
# ------------------------------------------------------------
# 有一个文件名 part_001_draft.STEP：
# 1. 转成小写。
# 2. 把 draft 改成 final。
# 3. 用 f-string 打印“最终文件名：...”。

file_name = "part_001_draft.STEP"
final_name = file_name.lower().replace("draft", "final")
print(f"最终文件名：{final_name}")

print("\n第 3 课结束：文字处理最常用的就是格式化、切片和方法。")
