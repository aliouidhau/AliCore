/* ============================================================
   C14：多文件与构建——先编译，再链接
   ============================================================
   【本课目标】
   1. 知道「编译单元」是什么：一个 .c 文件编译成一个 .o。
   2. 知道 .h 里放声明，.c 里放定义。
   3. 会看「先编译后链接」的两条命令。
   4. 知道 make / 构建脚本是干什么的（本机没有 make，用脚本代替）。

   【本机环境说明】
   TinyCC 支持 -c（只编译成 .o）和 -o（指定输出），
   所以真实项目那套「分开编译、最后链接」在这里能演示：

       tcc -c part_impl.c -o part_impl.o
       tcc -c main.c      -o main.o
       tcc part_impl.o main.o -o app.exe
       app.exe

   【为了你在这里能直接点运行】
   靶场一次只能运行一个 .c 文件，所以本课用
       #include "_lib/part_impl.c"
   把实现文件「并」进当前文件（这叫 unity build）。
   原理没变：先编译，再链接——只是把两步合成了一步。
   真实项目不要这么写，否则改一个文件要重编全部。
   ============================================================ */

#include <stdio.h>
#include <string.h>

/* 头文件里只有声明：告诉编译器"这个函数存在，长这样"。 */
#include "_lib/part_api.h"

/* 实现文件：本课为了能直接运行才并进来。真实项目由 -c 单独编译。 */
#include "_lib/part_impl.c"

/* --------------------------------------------------------
   一、一个 .c 文件 = 一个编译单元
   --------------------------------------------------------
   编译器一次只看一个 .c 文件。别的 .c 里的函数，它看不见。
   所以必须有一份「声明」告诉它：这个函数叫什么、参数什么类型、返回什么。

   声明放在 .h 里，谁要用就 #include 谁。
   定义（函数体）放在某个 .c 里，全项目只能有一份，否则链接时报
   multiple definition。

   二、链接：把一堆 .o 拼成一个程序
   --------------------------------------------------------
   每个 .o 里都有"我用到了 part_volume，但我不知道它在哪"的占位。
   链接器负责把这些占位和真正的实现接上。
   接不上就报 undefined reference（未定义引用）。

   这个错误几乎只有两个原因：
     1. 忘了把那个 .c 编进去（或者忘了 -o 时带上那个 .o）；
     2. 函数名拼错了（声明和定义不一致）。

   三、为什么非要分文件
   --------------------------------------------------------
   1. 编译快：改一个文件只重编一个。
   2. 多人协作不打架。
   3. 接口和实现分开：用的人只看 .h，不用关心实现。
   4. 课设要求"模块化设计"——分文件就是最基础的模块化。

   四、构建脚本：把一串命令固定下来
   --------------------------------------------------------
   每次敲三条命令太麻烦，所以有脚本。本机没有 make，用 .bat：

       @echo off
       tcc -c part_impl.c -o part_impl.o
       tcc -c main.c      -o main.o
       tcc part_impl.o main.o -o app.exe
       app.exe

   存成 build.bat，双击就跑。make 的作用一样，只是规则写在 Makefile 里、
   还会自动判断"哪个文件改了才重编哪个"。

   五、常见错误
   --------------------------------------------------------
   1. 在头文件里写函数体 → 被多个 .c include 后，链接报 multiple definition。
   2. 头文件没有 include 守卫 → 同一个文件里重复 include 就重复定义。
   3. 声明和定义参数类型不一致 → 链接过了，运行结果乱。
   4. 忘了加 -o → 生成了一堆 .o，没有可执行文件。

   六、动手练习
   1. 在 _lib/part_impl.c 里加一个 part_area（表面积），
      并在 part_api.h 里加声明，然后在本课里调用它。
   2. 把本课的 #include "_lib/part_impl.c" 删掉，看看会报什么错，
      体会什么叫「未定义引用」。（看完记得还原）
   3. 写一个 build.bat 的草稿，把三条命令抄对。
   -------------------------------------------------------- */

int main(void) {
    setbuf(stdout, NULL);

    printf("=== 用头文件里的声明，调用实现里的函数 ===\n");

    Part cube;
    strcpy(cube.name, "垫块");
    cube.length = 30.0;
    cube.width = 20.0;
    cube.height = 10.0;

    printf("零件：%s\n", cube.name);
    printf("体积：%.1f\n", part_volume(&cube));
    printf("质量（密度 2.7）：%.1f\n", part_mass(&cube, 2.7));
    printf("是否有效：%s\n", part_is_valid(&cube) ? "是" : "否");
    printf("规格：%s\n", part_grade(&cube));

    Part bad;
    strcpy(bad.name, "坏件");
    bad.length = 0.0;
    bad.width = 20.0;
    bad.height = 10.0;
    printf("\n长度填 0 的零件：有效=%s，体积=%.1f\n",
           part_is_valid(&bad) ? "是" : "否", part_volume(&bad));

    printf("\nC14 结束：一个 .c 编译成一个 .o，链接器再把它们拼起来。\n");
    return 0;
}
