# ============================================================
# 第 2 课：变量与数据类型
# ============================================================
# 【本课目标】
# 1. 理解变量是“给数据贴的名字”。
# 2. 认识字符串、整数、小数、布尔值。
# 3. 学会查看类型和做基本类型转换。

# ------------------------------------------------------------
# 一、变量：给数据起一个有意义的名字
# ------------------------------------------------------------
# 等号 = 不是数学里的“等于”，而是“把右边的值交给左边的名字”。
# 下面这行读作：把字符串 "阿鲤" 赋给变量 name。

name = "阿鲤"
age = 20

print(name)
print(age)

# 变量可以随时指向新值，后面的代码会使用新值。
age = 21
print("更新后的年龄：", age)

# ------------------------------------------------------------
# 二、四种最常用的数据类型
# ------------------------------------------------------------
# str   字符串：文字，必须加引号。
# int   整数：没有小数点的数字。
# float 浮点数：带小数点的数字。
# bool  布尔值：只有 True 和 False，注意首字母大写。

student_name = "学生甲"       # str
student_age = 20             # int
height = 1.75                # float
is_student = True            # bool

print("姓名类型：", type(student_name))
print("年龄类型：", type(student_age))
print("身高类型：", type(height))
print("是否学生：", type(is_student))

# type() 是老师查作业时常用的工具：不确定类型，就打印出来看看。

# ------------------------------------------------------------
# 三、为什么不能把文字和数字直接相加？
# ------------------------------------------------------------
# "20" 是文字，20 是数字，它们看起来像，类型却不同。
# 下面这行如果取消注释，会报 TypeError：
# print("年龄：" + 20)

# 正确做法 1：用逗号，让 print 分别处理。
print("年龄：", 20)

# 正确做法 2：把数字转成字符串，再拼接。
print("年龄：" + str(20))

# ------------------------------------------------------------
# 四、类型转换
# ------------------------------------------------------------
# int()   转成整数
# float() 转成小数
# str()   转成字符串

score_text = "95"
score_number = int(score_text)
print("转换后：", score_number + 5)

price_text = "19.9"
price = float(price_text)
print("两件价格：", price * 2)

# int("3.14") 会失败，因为整数字符串里不能带小数点。
# 可以先 float("3.14")，再 int(...) 得到 3。
print("3.14 转整数：", int(float("3.14")))

# ------------------------------------------------------------
# 五、变量命名规则与习惯
# ------------------------------------------------------------
# 可以用：字母、数字、下划线，但不能用数字开头。
# 推荐：见名知意，多个单词用下划线连接。
# 不推荐：a、b、c、data1，过几天自己都看不懂。

part_length = 80
part_width = 50
part_area = part_length * part_width
print("零件面积：", part_area)

# 合法但不推荐：x1 = 80
# 不合法：1part = 80

# ------------------------------------------------------------
# 六、课堂练习
# ------------------------------------------------------------
# 定义一个零件：名称是“支架”，长 120，宽 60，厚 8。
# 计算体积，并打印“支架的体积是 ... 立方毫米”。

part_name = "支架"
length = 120
width = 60
thickness = 8
volume = length * width * thickness
print(part_name, "的体积是", volume, "立方毫米")

print("\n第 2 课结束：变量负责保存数据，类型决定数据能怎样运算。")
