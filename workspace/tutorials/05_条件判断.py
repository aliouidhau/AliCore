# ============================================================
# 第 5 课：条件判断——让程序会做选择
# ============================================================
# 【本课目标】
# 1. 看懂比较运算得到 True / False。
# 2. 掌握 if、elif、else。
# 3. 会用 and、or、not 组合条件。

# ------------------------------------------------------------
# 一、比较的结果不是数字，而是布尔值
# ------------------------------------------------------------
# == 判断相等；= 才是赋值。初学者最常把这两个写反。

score = 76
print("score == 76：", score == 76)
print("score >= 60：", score >= 60)
print("score != 100：", score != 100)

# 常见比较符号：== 等于，!= 不等于，> 大于，< 小于，>=，<=。

# ------------------------------------------------------------
# 二、if：条件成立才执行
# ------------------------------------------------------------
# 注意两个格式：
# 1. 条件末尾有英文冒号。
# 2. 属于 if 的代码统一缩进 4 个空格。

temperature = 38

if temperature > 37:
    print("温度偏高")
    print("这行也属于 if，因为它同样缩进了")

print("这行不属于 if，总会执行")

# ------------------------------------------------------------
# 三、if...else：二选一
# ------------------------------------------------------------
# 条件成立走 if，不成立走 else，不会两边都走。

has_drawing = False

if has_drawing:
    print("开始按图纸加工")
else:
    print("先补图纸，再开始加工")

# ------------------------------------------------------------
# 四、elif：多个分支只走一个
# ------------------------------------------------------------
# Python 从上到下检查，遇到第一个成立的分支就执行，然后跳出整段。
# 所以范围条件要按合理顺序写。

score = 85

if score >= 90:
    level = "优秀"
elif score >= 80:
    level = "良好"
elif score >= 60:
    level = "及格"
else:
    level = "需要复习"

print("成绩等级：", level)

# 错误思路：把 score >= 60 放在最前面，85 分会直接被判为“及格”，
# 后面的“良好”“优秀”就没机会执行了。

# ------------------------------------------------------------
# 五、and、or、not
# ------------------------------------------------------------
# and：两个条件都成立才成立。
# or ：至少一个成立就成立。
# not：把真假反过来。

age = 20
has_id = True

if age >= 18 and has_id:
    print("年龄和证件条件都满足")

is_weekend = True
is_holiday = False
if is_weekend or is_holiday:
    print("今天可以安排自习")

if not is_holiday:
    print("今天不是法定节假日")

# ------------------------------------------------------------
# 六、嵌套：条件里面还能有条件
# ------------------------------------------------------------
# 能用一层说清楚，就别叠太多层。嵌套太深会难读。

material = "铝合金"
thickness = 8

if material == "铝合金":
    if thickness >= 6:
        print("铝合金，厚度满足要求")
    else:
        print("铝合金，但厚度偏薄")
else:
    print("当前课程只演示铝合金")

# ------------------------------------------------------------
# 七、课堂练习：尺寸是否合格
# ------------------------------------------------------------
# 某轴要求直径在 19.8 到 20.2 mm 之间（包含边界）。
# 给一个测量值，打印“合格”或“不合格”。

measured_diameter = 20.05

if 19.8 <= measured_diameter <= 20.2:
    print("轴径合格")
else:
    print("轴径不合格")

# Python 支持 19.8 <= x <= 20.2 这种连续比较，读起来接近数学。

print("\n第 5 课结束：条件判断的核心，是把现实规则翻译成真假条件。")
