/* ============================================================
   C04：函数与递归——把代码拆成可复用的零件
   ============================================================
   【本课目标】
   1. 会声明、定义、调用函数。
   2. 理解参数传递和返回值。
   3. 会用递归，也知道递归必须有终止条件。
   4. 知道函数原型（prototype）为什么有用。

   本课不需要输入。
   ============================================================ */

#include <stdio.h>

/* ------------------------------------------------------------
   一、函数原型
   ------------------------------------------------------------
   在 main 之前先告诉编译器：这个函数叫什么、收什么、返回什么。
   这样 main 可以调用后面才定义的函数。 */
int square(int value);
int factorial_iter(int n);
int factorial_rec(int n);
int gcd(int a, int b);

int main(void) {
    setbuf(stdout, NULL);

    int n = 6;

    /* --------------------------------------------------------
       二、调用函数
       --------------------------------------------------------
       函数名后面加括号，传入实参。
       返回值可以赋给变量，也可以直接放进 printf。 */
    printf("%d 的平方：%d\n", n, square(n));
    printf("%d 的阶乘（循环）：%d\n", n, factorial_iter(n));
    printf("%d 的阶乘（递归）：%d\n", n, factorial_rec(n));

    /* --------------------------------------------------------
       三、递归
       --------------------------------------------------------
       递归就是函数调用自己。
       关键是：每一层都要把问题缩小，并且有终止条件。
       以阶乘为例：6! = 6 * 5!，5! = 5 * 4!，直到 1! = 1。 */
    printf("\n递归展开：\n");
    printf("factorial_rec(3) = 3 * factorial_rec(2)\n");
    printf("factorial_rec(2) = 2 * factorial_rec(1)\n");
    printf("factorial_rec(1) = 1  <- 终止条件\n");

    /* --------------------------------------------------------
       四、多个参数
       --------------------------------------------------------
       函数可以接收多个参数，按顺序传入。 */
    printf("\ngcd(48, 18) = %d\n", gcd(48, 18));

    /* --------------------------------------------------------
       五、值传递
       --------------------------------------------------------
       C 默认按值传递：函数拿到的是副本。
       在函数里改参数，不会影响调用者的变量。
       想修改调用者的变量，要传指针（下一课讲）。 */
    int original = 10;
    int copy = square(original);
    printf("\noriginal 仍然是：%d\n", original);
    printf("square 的返回值：%d\n", copy);

    /* --------------------------------------------------------
       六、常见错误
       --------------------------------------------------------
       1. 递归没有终止条件，栈会溢出。
       2. 函数声明和定义的参数类型不一致。
       3. 函数返回类型写了 int，却 return 一个字符串。
       4. 把数组当参数时，数组会退化成指针，长度要另外传。
       5. 函数名和变量名重名，阅读困难。

       七、动手练习
       1. 写一个 max3(a,b,c)，返回三个数中的最大值。
       2. 写一个递归函数 sum_to(n)，返回 1+2+...+n。
       3. 写一个递归版斐波那契，再思考它为什么慢。
       -------------------------------------------------------- */

    printf("\nC04 结束：函数要小、名字要准、返回值要明确。\n");
    return 0;
}

int square(int value) {
    return value * value;
}

int factorial_iter(int n) {
    int result = 1;
    int i;
    if (n < 0) {
        return -1;  /* 用 -1 表示非法输入；正式项目应单独处理错误。 */
    }
    for (i = 2; i <= n; i++) {
        result *= i;
    }
    return result;
}

int factorial_rec(int n) {
    if (n <= 1) {
        return 1;   /* 终止条件 */
    }
    return n * factorial_rec(n - 1);  /* 问题缩小 */
}

int gcd(int a, int b) {
    /* 欧几里得算法：gcd(a,b) = gcd(b, a % b)，直到余数为 0。 */
    if (b == 0) {
        return a;
    }
    return gcd(b, a % b);
}
