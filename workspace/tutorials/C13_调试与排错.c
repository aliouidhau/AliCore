/* ============================================================
   C13：调试与排错——先定位，再动手
   ============================================================
   【本课目标】
   1. 看到编译错误，知道第一步看哪里。
   2. 程序崩了，会用 printf 二分法把范围缩到几行。
   3. 会用 assert 守住"我认为一定成立"的假设。
   4. 记住运行崩溃的四个常见来源。

   【本机环境说明（重要）】
   这台机器只有 TinyCC，没有安装 gdb 调试器。
   所以本课教的是「没有调试器时最有效的三招」：
     读错误信息 → printf 二分 → assert 守假设
   等以后装了 gdb，再学断点/单步；那只是把这三招做得更快。

   本课不需要输入。慢慢看输出，对比注释。
   ============================================================ */

#include <stdio.h>
#include <assert.h>

/* --------------------------------------------------------
   一、编译错误怎么读（四步）
   --------------------------------------------------------
   编译错误的信息长这样：

       C13.c:42: error: 'x' undeclared (first use in this function)

   四步读法：
     1. 先看 文件:行号 —— 直接跳过去；
     2. 再看 error: 后面那个词 —— undeclared / expected ';' / too few arguments；
     3. 然后往上看一两行 —— 真正的位置常在上面一行（比如上一行少了分号）；
     4. 一次只修一个错误，重新编译。

   注意：第一个错误后面的错误，往往是被第一个错误带出来的。
   修完第一个再看，不要一口气全文乱改。

   下面这段演示一个「编译能过、但逻辑错」的函数：
   编译错误只能保证语法对，逻辑对不对要靠运行和断言。 */

int average(int sum, int count) {
    /* 如果 count 是 0，这里就会除零。先守住假设： */
    assert(count > 0 && "average: count 不能为 0");
    return sum / count;
}

/* --------------------------------------------------------
   二、printf 二分法：定位"哪一行开始不对"
   --------------------------------------------------------
   程序崩溃或结果不对时，别乱猜。在函数开头、中间、结尾各打一行，
   看输出停在哪一行。范围大就再对半劈——这叫二分。

   例：一个函数 20 行，崩在中间。
     1. 在第 10 行前打 printf("A\n");
     2. 如果 A 打出来了，说明前 10 行没问题，问题在后 10 行；
     3. 再找后 10 行的中点，打 B；
     4. 二十行的范围，三次就能缩到 2-3 行。
   -------------------------------------------------------- */

int sum_to(int n) {
    int total = 0;
    int i;
    for (i = 1; i <= n; i++) {
        total += i;
        /* 想知道循环到底走到哪一步，就在这里打一行。
           平时要删掉，或者用 #ifdef DEBUG 包起来。 */
    }
    return total;
}

/* --------------------------------------------------------
   三、assert：把"我以为"写成代码
   --------------------------------------------------------
   assert(条件) 在条件不成立时会打印行号并直接中止程序。

   它最有用的时候：你坚信某个值一定满足某个范围。
   只要它不满足，程序就应该立刻停下——因为后面所有计算都不可信了。

   正式发布时可以用 #define NDEBUG 把它关掉（编译加 -DNDEBUG）。 */

int part_index(int number, int total) {
    /* 零件编号从 1 开始，下标从 0 开始，转换时必须守住边界。 */
    assert(total > 0);
    assert(number >= 1 && number <= total);
    return number - 1;
}

/* --------------------------------------------------------
   四、运行崩溃的四个常见来源
   --------------------------------------------------------
   1. 数组越界写：int a[3]; a[3] = 1;   —— 越界一格不报错，但会覆盖邻居。
   2. 野指针：int *p; *p = 5;           —— p 没指向有效内存，直接崩。
   3. 除以零：int x = 10 / 0;           —— 进程被杀，没有"错误信息"。
   4. 空指针解引用：int *p = NULL; *p;  —— 崩。
   共同点：它们不是"报错"，是程序直接死。所以只能靠断言和边界检查提前拦住。 */

int safe_get(const int *data, int size, int index, int fallback) {
    if (data == NULL) {
        return fallback;
    }
    if (index < 0 || index >= size) {
        return fallback;
    }
    return data[index];
}

/* --------------------------------------------------------
   五、调试的顺序（照这个走，别跳步）
   --------------------------------------------------------
   第 1 步：先让编译通过（一次修一个错误）。
   第 2 步：跑起来看输出对不对（对不上，先确认输入对不对）。
   第 3 步：不对就二分打印，找到出问题的那一行。
   第 4 步：在那一行附近写 assert，把假设钉死，防止它以后再坏。
   第 5 步：修完把调试打印删掉，或者用 #ifdef DEBUG 包起来。

   六、动手练习
   1. 故意把 part_index 的 assert 改成 number <= total + 1，
      在 main 里调 part_index(6, 5)，看它怎么拦住你。
   2. 把 sum_to 里的 total += i 改成 total += 1，想想输出会变成什么，
      再运行验证你的推测。
   3. 写一个函数 int div_or(int a, int b, int fallback)：
      b 为 0 时返回 fallback，否则返回 a / b。用 assert 守住 fallback 的使用。
   -------------------------------------------------------- */

int main(void) {
    setbuf(stdout, NULL);

    printf("=== 一、assert 守假设 ===\n");
    printf("average(90, 3) = %d\n", average(90, 3));
    printf("part_index(3, 5) = %d\n", part_index(3, 5));

    printf("\n=== 二、二分打印的落点 ===\n");
    printf("sum_to(10) = %d\n", sum_to(10));

    printf("\n=== 三、越界要自己拦 ===\n");
    int data[3] = {10, 20, 30};
    printf("safe_get(0) = %d\n", safe_get(data, 3, 0, -1));
    printf("safe_get(2) = %d\n", safe_get(data, 3, 2, -1));
    printf("safe_get(3) = %d（越界，给了兜底值）\n", safe_get(data, 3, 3, -1));
    printf("safe_get(NULL) = %d（空指针，给了兜底值）\n", safe_get(NULL, 3, 0, -1));

    printf("\nC13 结束：调试不是猜，是缩小范围。\n");
    return 0;
}
