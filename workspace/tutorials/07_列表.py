# ------------------------------------------------------------
# 一、列表是什么？
# ------------------------------------------------------------
# 列表用方括号，元素之间用逗号。
# 它有顺序、能修改、允许重复，是最常用的数据容器之一。

parts = ["底座", "支架", "盖板", "支架"]
print("完整列表：", parts)
print("元素数量：", len(parts))

# 列表也能装数字，甚至混合类型；实际使用时建议一个列表装同类数据。
measurements = [20.01, 19.95, 20.10]
print("测量值：", measurements)

# ------------------------------------------------------------
# 二、下标与切片
# ------------------------------------------------------------
# 下标从 0 开始；-1 表示最后一个。
# 越界会报 IndexError，所以先确认列表里确实有那个位置。

print("第一个：", parts[0])
print("最后一个：", parts[-1])
print("前两个：", parts[:2])
print("从第二个开始：", parts[1:])

# ------------------------------------------------------------
# 三、修改、添加、删除
# ------------------------------------------------------------
# 列表和字符串不同：列表可以直接修改某个位置的内容。

parts[0] = "加强底座"
print("修改后：", parts)

parts.append("螺钉")          # 末尾添加一个元素
print("append 后：", parts)

parts.insert(1, "垫片")       # 在指定位置插入
print("insert 后：", parts)

parts.remove("支架")          # 只删除第一个匹配到的“支架”
print("remove 后：", parts)

removed = parts.pop()         # 删除并返回最后一个元素
print("pop 删掉的元素：", removed)
print("pop 后：", parts)

# ------------------------------------------------------------
# 四、查找与统计
# ------------------------------------------------------------
# in 判断是否存在；count 统计出现次数；index 找第一次出现的位置。

numbers = [3, 7, 3, 9]
print("7 是否存在：", 7 in numbers)
print("3 出现次数：", numbers.count(3))
print("7 的位置：", numbers.index(7))

# index 找不到会报错，不确定时先用 in 判断。

# ------------------------------------------------------------
# 五、排序
# ------------------------------------------------------------
# sort 会直接修改原列表；reverse=True 表示从大到小。

scores = [88, 72, 95, 80]
scores.sort()
print("从小到大：", scores)

scores.sort(reverse=True)
print("从大到小：", scores)

# sorted 会返回一个新列表，不改原列表。
original = [3, 1, 2]
new_list = sorted(original)
print("原列表：", original)
print("新列表：", new_list)

# ------------------------------------------------------------
# 六、列表推导式
# ------------------------------------------------------------
# 当你想“根据旧列表生成新列表”时，推导式很简洁。
# 下面读作：对每个 n，把 n*n 放进新列表。

numbers = [1, 2, 3, 4, 5]
squares = [n * n for n in numbers]
print("平方列表：", squares)

# 加条件：只保留偶数，再计算平方。
even_squares = [n * n for n in numbers if n % 2 == 0]
print("偶数平方：", even_squares)

# 等价于：
# even_squares = []
# for n in numbers:
#     if n % 2 == 0:
#         even_squares.append(n * n)

# ------------------------------------------------------------
# 七、课堂练习：测量数据统计
# ------------------------------------------------------------
# 找出所有合格轴径，放进新列表，再计算合格率的百分比。

measurements = [20.01, 19.75, 20.10, 20.30, 19.90, 20.00]
qualified = [v for v in measurements if 19.8 <= v <= 20.2]
pass_rate = len(qualified) / len(measurements)

print("合格数据：", qualified)
print(f"合格率：{pass_rate:.1%}")

