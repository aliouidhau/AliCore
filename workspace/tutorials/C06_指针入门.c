/* ============================================================
   C06：指针入门——变量地址也是一张纸条
   ============================================================
   【本课目标】
   1. 理解变量有地址，指针保存地址。
   2. 会用 & 取地址、* 解引用。
   3. 会用指针修改调用者的变量。
   4. 知道指针算术和空指针的基本概念。

   本课不需要输入。指针是 C 的分水岭，慢一点没关系。
   ============================================================ */

#include <stdio.h>

void swap_wrong(int a, int b);
void swap(int *a, int *b);

int main(void) {
    setbuf(stdout, NULL);

    /* --------------------------------------------------------
       一、地址与解引用
       --------------------------------------------------------
       &value 取得变量地址；指针变量保存这个地址。
       *pointer 顺着地址找到那个变量。 */
    int value = 42;
    int *pointer = &value;

    printf("value 的值：%d\n", value);
    printf("value 的地址：%p\n", (void *)&value);
    printf("pointer 保存的地址：%p\n", (void *)pointer);
    printf("通过 pointer 读到的值：%d\n", *pointer);

    /* 通过指针写，会改到原变量。 */
    *pointer = 99;
    printf("修改后 value = %d\n", value);

    /* --------------------------------------------------------
       二、值传递 vs 指针传递
       --------------------------------------------------------
       普通参数是副本，函数里怎么改都不影响外面。
       传指针，函数拿到地址，才能改外面的变量。 */
    int x = 10;
    int y = 20;

    printf("\n交换前：x=%d, y=%d\n", x, y);
    swap_wrong(x, y);
    printf("值传递交换后：x=%d, y=%d（没有变化）\n", x, y);

    swap(&x, &y);
    printf("指针交换后：x=%d, y=%d\n", x, y);

    /* --------------------------------------------------------
       三、指针与数组
       --------------------------------------------------------
       数组名在多数表达式里会退化成首元素地址。
       pointer + 1 不是加一个字节，而是加一个元素的大小。 */
    int data[4] = {5, 10, 15, 20};
    int *cursor = data;

    printf("\n用指针遍历数组：\n");
    int i;
    for (i = 0; i < 4; i++) {
        printf("  cursor[%d] = %d，地址 = %p\n", i, *(cursor + i), (void *)(cursor + i));
    }

    cursor = data;
    printf("cursor 自增前：%d\n", *cursor);
    cursor++;
    printf("cursor 自增后：%d\n", *cursor);

    /* --------------------------------------------------------
       四、空指针
       --------------------------------------------------------
       指针不指向任何有效对象时，应该设为 NULL。
       使用前必须检查，不能直接解引用。 */
    int *nothing = NULL;
    if (nothing == NULL) {
        printf("\n空指针不能解引用，这里只做检查。\n");
    }

    /* --------------------------------------------------------
       五、常见错误
       --------------------------------------------------------
       1. 解引用未初始化指针，程序崩溃。
       2. 把普通整数当地址传给指针。
       3. 指针类型不匹配，例如 int* 指向 double。
       4. 数组越界后用指针继续走，读到垃圾数据。
       5. 以为 *p++ 和 (*p)++ 一样；优先级不同。

       六、动手练习
       1. 写一个函数，用指针把两个 double 相加并写回第一个参数。
       2. 用指针遍历数组，找出最大值。
       3. 画一张图：变量 value、指针 pointer、地址 0x... 的关系。
       -------------------------------------------------------- */

    printf("\nC06 结束：指针不是魔法，它只是地址。\n");
    return 0;
}

void swap_wrong(int a, int b) {
    int temp = a;
    a = b;
    b = temp;
    /* a、b 是副本，函数结束后就消失。 */
}

void swap(int *a, int *b) {
    int temp = *a;
    *a = *b;
    *b = temp;
}
