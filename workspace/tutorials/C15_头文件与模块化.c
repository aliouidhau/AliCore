/* ============================================================
   C15：头文件与模块化——接口和实现分开
   ============================================================
   【本课目标】
   1. 会写 include 守卫，知道不加会出什么事。
   2. 分清「声明」和「定义」，知道 .h 里该放什么、不该放什么。
   3. 会用 static 把函数限制在本文件内。
   4. 理解一个结构体怎么被多个文件共用。

   【和 C14 的区别】
   C14 讲「怎么构建」（编译单元、.o、链接）。
   C15 讲「怎么切分」（哪些内容放头文件、怎么防止重复定义）。
   ============================================================ */

#include <stdio.h>
#include <string.h>

/* --------------------------------------------------------
   一、include 守卫
   --------------------------------------------------------
   头文件的标准写法：

       #ifndef PART_API_H
       #define PART_API_H
       ... 内容 ...
       #endif

   为什么必须有：
   头文件会被多个 .c include，也可能被同一个 .c 间接 include 两次。
   没有守卫，第二次 include 时结构体、typedef 会重复定义，编译直接报错。

   下面故意 include 两次，看守卫怎么兜住：
   -------------------------------------------------------- */

#include "_lib/part_api.h"
#include "_lib/part_api.h"   /* 第二次：守卫让内容不重复展开 */

/* 实现文件（本课为了能直接运行才并进来） */
#include "_lib/part_impl.c"

/* --------------------------------------------------------
   二、.h 放什么、不放什么
   --------------------------------------------------------
   放：
     · 函数声明（原型）
     · 结构体 / 枚举 / typedef 定义
     · 宏常量
     · extern 变量声明

   不放：
     · 函数体（除非是 static inline）
     · 全局变量定义（int g_count = 0;）—— 多个 .c include 后会重复定义
     · 只在某个 .c 里用的内部函数

   三、extern 与 static
   --------------------------------------------------------
   extern int g_total;   声明：这个变量在别的文件里定义
   int g_total = 0;      定义：真正分配内存，全项目只能有一份

   static int helper(void) { ... }
   加了 static 的函数/全局变量，只在「本编译单元」可见。
   这是模块化的关键：内部实现不该暴露给外面。
   -------------------------------------------------------- */

/* 四、动手看效果：外部只认头文件里的东西
   --------------------------------------------------------
   下面调用的函数都在 _lib/part_impl.c 里实现，
   本文件只看得到 _lib/part_api.h 里的声明。
   改实现不用改头文件，用的人也不用改。 */

static int local_counter = 0;   /* static 全局：只在本文件可见 */

static void count_call(void) {
    local_counter++;
}

/* 五、常见错误
   --------------------------------------------------------
   1. 头文件忘写守卫 → 重复定义。
   2. 把函数体写进头文件 → 被两个 .c include 后 multiple definition。
   3. 在头文件里定义全局变量 → 同上。
   4. 声明和定义的参数类型不一致 → 编译过了、运行结果不对。
   5. 头文件路径写错 → 报 No such file，先看 -I 和相对路径。

   六、动手练习
   1. 把本课第二次 include 的守卫临时删掉（改 _lib/part_api.h），
      看编译报什么错，再还原。
   2. 在 part_api.h 里加 part_area 的声明，在 part_impl.c 里实现，
      然后在本课调用。
   3. 给 part_impl.c 加一个 static 内部辅助函数，验证 main 里调用它会报错。
   -------------------------------------------------------- */

int main(void) {
    setbuf(stdout, NULL);

    printf("=== 守卫生效：头文件被 include 两次也没重复定义 ===\n");

    Part p;
    strcpy(p.name, "轴套");
    p.length = 50.0;
    p.width = 20.0;
    p.height = 20.0;

    printf("零件：%s\n", p.name);
    printf("体积：%.1f\n", part_volume(&p));
    printf("质量：%.1f\n", part_mass(&p, 7.85));
    printf("规格：%s\n", part_grade(&p));

    printf("\n=== static 内部函数：只在实现文件里可见 ===\n");
    part_volume(&p);
    part_volume(&p);
    count_call();
    count_call();
    count_call();
    printf("实现内部记录的调用次数：%d\n", part_internal_calls());
    printf("本文件自己的计数：%d\n", local_counter);

    printf("\nC15 结束：头文件是契约，实现文件是履约。\n");
    return 0;
}
