# ------------------------------------------------------------
# 一、为什么需要函数？
# ------------------------------------------------------------
# 假设同一个“矩形面积”公式在程序里用了十次。
# 如果每次都重写，公式一旦改错，就要改十个地方。
# 函数把公式集中起来：定义一次，使用多次。

def rectangle_area(length, width):
    """计算矩形面积。length 和 width 是输入参数。"""
    area = length * width
    return area


# 上面只是“定义”，还不会自动执行。
# 真正让函数工作的是下面的“调用”：函数名加括号。

result = rectangle_area(80, 50)
print("80 × 50 的面积：", result)
print("120 × 60 的面积：", rectangle_area(120, 60))

# ------------------------------------------------------------
# 二、参数与返回值
# ------------------------------------------------------------
# 参数：函数需要的输入。
# return：函数交给调用者的结果。
# 没有 return 的函数，默认返回 None。

def show_part(name):
    print("正在显示零件：", name)
    # 这里没有 return


returned = show_part("支架")
print("show_part 的返回值：", returned)

# print 是“给人看”，return 是“给程序继续用”，两者不要混淆。

# ------------------------------------------------------------
# 三、默认参数与关键字参数
# ------------------------------------------------------------
# 默认参数：调用时不传，就使用默认值。
# 有默认值的参数要放在没有默认值的参数后面。

def greet(name, greeting="你好"):
    return f"{greeting}，{name}"


print(greet("学生甲"))
print(greet("学生甲", "早上好"))
print(greet(name="阿鲤", greeting="晚上好"))

# 参数较多时，写“参数名=值”会更清楚，也不怕顺序记错。

# ------------------------------------------------------------
# 四、函数可以调用别的函数
# ------------------------------------------------------------
# 大任务可以拆成几个小函数，每个函数只负责一件事。

def rectangle_volume(length, width, height):
    area = rectangle_area(length, width)
    return area * height


volume = rectangle_volume(80, 50, 10)
print("矩形块体积：", volume)

# 这种拆法的好处：面积公式有问题，只需要修 rectangle_area。

# ------------------------------------------------------------
# 五、变量作用域：函数里面的名字
# ------------------------------------------------------------
# 在函数内部创建的变量，通常是局部变量，出了函数就不能直接用。
# 需要把结果带出来，就用 return。

def calculate_double(number):
    doubled = number * 2
    return doubled


print("翻倍结果：", calculate_double(21))
# print(doubled)  # 会报 NameError，因为 doubled 只在函数内部存在

# ------------------------------------------------------------
# 六、给函数写说明
# ------------------------------------------------------------
# 函数名下面紧跟的三引号文字叫文档字符串 docstring。
# 它说明用途、参数和返回值，方便以后查看。

def is_diameter_qualified(value, minimum=19.8, maximum=20.2):
    """判断轴径是否在允许范围内，包含上下边界。"""
    return minimum <= value <= maximum


print("20.05 是否合格：", is_diameter_qualified(20.05))
print("20.30 是否合格：", is_diameter_qualified(20.30))

# ------------------------------------------------------------
# 七、课堂练习：批量计算体积
# ------------------------------------------------------------
# 写一个函数，接收长、宽、高，返回体积。
# 再用循环计算三组尺寸，并逐行打印。

def volume_of_box(length, width, height):
    """返回长方体体积，单位由输入尺寸决定。"""
    return length * width * height


sizes = [
    (80, 50, 10),
    (120, 60, 8),
    (30, 30, 30),
]

for index, (l, w, h) in enumerate(sizes, start=1):
    v = volume_of_box(l, w, h)
    print(f"第 {index} 组：{l}×{w}×{h}，体积 {v}")

print("\n第 9 课结束：好函数应该名字清楚、职责单一、结果可复用。")
